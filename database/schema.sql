-- 13. DASHBOARD VIEW (14 summary metrics used by src/pages/Dashboard.jsx)
-- =============================================================================
create or replace view public.vw_dashboard_metrics as
select
  (select count(*) from public.members)                                                        as total_members,
  (select count(*) from public.members where status = 'Active')                                as active_members,
  (select count(*) from public.members where status in ('Inactive','Expired'))                 as inactive_members,
  (select count(*) from public.admission_submissions where status = 'Pending')                  as pending_applications,
  (select count(*) from public.plans where status = 'Active')                                  as total_plans,
  (select count(*) from public.employees where status = 'Active')                              as total_employees,
  (select remaining_balance from public.sms_settings limit 1)                                  as remaining_sms,
  (select coalesce(sum(net_payable), 0) from public.invoices
     where date_trunc('month', invoice_date) = date_trunc('month', current_date))              as monthly_sales,
  (select coalesce(sum(net_payable), 0) from public.invoices where invoice_date = current_date) as today_sales_invoice,
  (select coalesce(sum(amount), 0) from public.payments
     where payment_date::date = current_date)                                                  as today_sales_payment,
  (select coalesce(sum(amount), 0) from public.expenses
     where date_trunc('month', expense_date) = date_trunc('month', current_date))              as monthly_expense,
  (select count(*) from public.members
     where date_trunc('month', joined) = date_trunc('month', current_date))                    as monthly_admissions,
  (select count(*) from public.members where expiry = current_date)                            as expiring_today,
  (select count(*) from public.attendance
     where attendance_date = current_date and status = 'In')                                   as present_members_now;

