-- Auto member code: FLM-000123 (members.member_code may also be set manually)
create or replace function public.set_member_code()
returns trigger
language plpgsql
as $$
begin
  if new.member_code is null then
    update public.members
       set member_code = 'FLM-' || lpad(new.id::text, 6, '0')
     where id = new.id;
  end if;
  return null;
end;
$$;

create or replace trigger trg_members_code
  after insert on public.members
  for each row execute function public.set_member_code();

-- Auto-create a staff profile row when a Supabase Auth user is created
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.users (auth_uid, email, name)
  values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data ->> 'name', split_part(new.email, '@', 1))
  )
  on conflict (auth_uid) do nothing;
  return new;
end;
$$;

create or replace trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

