create table public.roles (
  id                    bigint generated by default as identity primary key,
  name                  text not null unique,          -- 'Super Admin', 'Branch Manager', 'Receptionist', 'Trainer', 'Accountant'
  description           text,
  can_apply_discount    boolean default false,
  max_discount_percentage numeric(5,2) default 0.00,
  can_approve_members   boolean default false,
  can_manage_lockers    boolean default true,
  can_manage_finances   boolean default false,
  created_at            timestamptz default now(),
  updated_at            timestamptz default now()
);

create table public.permissions (
  id          bigint generated by default as identity primary key,
  module      text not null,        -- 'members', 'accounts', 'attendance', 'discounts'...
  action      text not null,        -- 'create', 'read', 'update', 'delete', 'approve'
  description text,
  unique (module, action)
);

create table public.role_permissions (
  role_id       bigint not null references public.roles(id) on delete cascade,
  permission_id bigint not null references public.permissions(id) on delete cascade,
  primary key (role_id, permission_id)
);

-- Staff/system accounts. Login credentials live in Supabase Auth;
-- this table holds profile + role. Linked 1:1 via auth_uid.
create table public.users (
  id          bigint generated by default as identity primary key,
  auth_uid    uuid unique references auth.users(id) on delete cascade,
  role_id     bigint references public.roles(id),
  name        text not null,
  email       text not null unique,
  phone       text,
  avatar      text,
  status      text not null default 'Active' check (status in ('Active','Inactive','Suspended')),
  last_login_at timestamptz,
  created_at  timestamptz default now(),
  updated_at  timestamptz default now()
);

