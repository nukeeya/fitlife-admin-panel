-- =============================================================================
-- 023: Commands from the server to the door machine
-- =============================================================================
-- The machine can't be called directly. It asks the receiver for work every few
-- seconds (/iclock/getrequest), runs one command, then reports the result
-- (/iclock/devicecmd).
--
--   * Commands are handed out one at a time, oldest first.
--   * A command is sent once and never retried automatically: a resent "enroll"
--     would prompt the machine again.
--   * A command still waiting after 10 minutes expires, so an old enrollment
--     can't pop up when the machine comes back online later.
--
-- Staff can read commands. For now they can only be added from the SQL Editor;
-- buttons in the app come after the commands are proven on the real machine.
--
-- Run after 022.

begin;

create table if not exists public.device_commands (
  id           bigint generated by default as identity primary key,
  device_id    bigint not null references public.devices(id) on delete restrict,
  command      text not null,
  status       text not null default 'queued'
               check (status in ('queued', 'sent', 'done', 'failed', 'expired')),
  return_code  int,
  created_at   timestamptz not null default now(),
  sent_at      timestamptz,
  finished_at  timestamptz
);

create index if not exists idx_device_commands_pending
  on public.device_commands(device_id, id) where status in ('queued', 'sent');

-- Returns the next command as the machine expects it (C:<id>:<command>), or null.
create or replace function public.next_device_command(p_serial text)
returns text
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_device_id bigint;
  v_id        bigint;
  v_command   text;
begin
  select id into v_device_id
    from public.devices
   where serial_number = p_serial and enabled;

  if v_device_id is null then
    return null;
  end if;

  update public.device_commands
     set status = 'expired', finished_at = now()
   where device_id = v_device_id
     and status = 'queued'
     and created_at < now() - interval '10 minutes';

  -- Wait for the machine to answer the last command (or for 2 minutes to pass).
  if exists (
    select 1 from public.device_commands
     where device_id = v_device_id
       and status = 'sent'
       and sent_at > now() - interval '2 minutes'
  ) then
    return null;
  end if;

  select id, command into v_id, v_command
    from public.device_commands
   where device_id = v_device_id and status = 'queued'
   order by id
   limit 1
   for update skip locked;

  if v_id is null then
    return null;
  end if;

  update public.device_commands
     set status = 'sent', sent_at = now()
   where id = v_id;

  return format('C:%s:%s', v_id, v_command);
end;
$$;

-- A return code of 0 means the machine accepted the command.
create or replace function public.record_device_command_result(
  p_serial      text,
  p_command_id  bigint,
  p_return_code int
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  update public.device_commands c
     set status      = case when p_return_code = 0 then 'done' else 'failed' end,
         return_code = p_return_code,
         finished_at = now()
    from public.devices d
   where c.id = p_command_id
     and c.device_id = d.id
     and d.serial_number = p_serial
     and c.status = 'sent';
end;
$$;

revoke all on function public.next_device_command(text) from public, anon, authenticated;
revoke all on function public.record_device_command_result(text, bigint, int) from public, anon, authenticated;
grant execute on function public.next_device_command(text) to service_role;
grant execute on function public.record_device_command_result(text, bigint, int) to service_role;

alter table public.device_commands enable row level security;

grant select on public.device_commands to authenticated;

drop policy if exists "staff read device commands" on public.device_commands;
create policy "staff read device commands" on public.device_commands
  for select to authenticated using (public.is_staff());

commit;
