-- Coffee shop point-of-sale records and atomic checkout for authenticated staff.
alter table public.shop_products
  drop constraint if exists shop_products_category_check;
alter table public.shop_products
  add constraint shop_products_category_check
  check (category in ('Gym Wear', 'Food', 'Cafe'));

create table if not exists public.coffee_shop_sales (
  id bigint generated by default as identity primary key,
  customer_name text not null default 'Walk-in Customer'
    check (char_length(trim(customer_name)) between 2 and 100),
  payment_method text not null
    check (payment_method in ('Cash', 'bKash', 'Card')),
  items jsonb not null
    check (jsonb_typeof(items) = 'array' and jsonb_array_length(items) between 1 and 100),
  total numeric(12, 2) not null check (total > 0),
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists idx_coffee_shop_sales_created_at
  on public.coffee_shop_sales(created_at desc);

alter table public.coffee_shop_sales enable row level security;

drop policy if exists "authenticated read coffee shop sales" on public.coffee_shop_sales;
create policy "authenticated read coffee shop sales"
  on public.coffee_shop_sales for select to authenticated
  using (true);

revoke all on table public.coffee_shop_sales from public, anon, authenticated;
grant select on table public.coffee_shop_sales to authenticated;

create or replace function public.complete_coffee_shop_sale(
  p_items jsonb,
  p_payment_method text,
  p_customer_name text default null
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_entry jsonb;
  v_product record;
  v_product_id bigint;
  v_quantity integer;
  v_seen_ids bigint[] := '{}';
  v_items jsonb := '[]'::jsonb;
  v_total numeric(12, 2) := 0;
  v_customer_name text := coalesce(nullif(trim(p_customer_name), ''), 'Walk-in Customer');
  v_sale_id bigint;
begin
  if coalesce(jsonb_typeof(p_items), '') <> 'array' then
    raise exception 'Add at least one item to the sale.';
  end if;
  if jsonb_array_length(p_items) not between 1 and 100 then
    raise exception 'Add at least one item to the sale.';
  end if;

  if coalesce(p_payment_method, '') not in ('Cash', 'bKash', 'Card') then
    raise exception 'Select a valid payment method.';
  end if;

  if char_length(v_customer_name) not between 2 and 100 then
    raise exception 'Customer name must be between 2 and 100 characters.';
  end if;

  -- Lock products in a consistent order so simultaneous checkouts cannot oversell.
  for v_entry in
    select value
    from jsonb_array_elements(p_items)
    order by value->>'product_id'
  loop
    if coalesce(v_entry->>'product_id', '') !~ '^[1-9][0-9]*$'
      or coalesce(v_entry->>'quantity', '') !~ '^[1-9][0-9]*$' then
      raise exception 'Sale items contain an invalid product or quantity.';
    end if;

    v_product_id := (v_entry->>'product_id')::bigint;
    v_quantity := (v_entry->>'quantity')::integer;

    if v_product_id = any(v_seen_ids) then
      raise exception 'A menu item appears more than once in the sale.';
    end if;
    if v_quantity < 1 or v_quantity > 100 then
      raise exception 'Item quantities must be between 1 and 100.';
    end if;

    select id, name, category, price, stock, unit
      into v_product
      from public.shop_products
      where id = v_product_id
        and category = 'Cafe'
        and status = 'Active'
      for update;

    if not found then
      raise exception 'A menu item is no longer available.';
    end if;
    if v_product.price <= 0 then
      raise exception 'A menu item has an invalid price. Update its menu listing first.';
    end if;
    if v_product.stock < v_quantity then
      raise exception 'Not enough stock for "%".', v_product.name;
    end if;

    update public.shop_products
      set stock = stock - v_quantity
      where id = v_product.id;

    v_seen_ids := array_append(v_seen_ids, v_product_id);
    v_total := v_total + v_product.price * v_quantity;
    v_items := v_items || jsonb_build_array(jsonb_build_object(
      'productId', v_product.id,
      'name', v_product.name,
      'price', v_product.price,
      'quantity', v_quantity,
      'unit', v_product.unit
    ));
  end loop;

  insert into public.coffee_shop_sales (
    customer_name, payment_method, items, total, created_by
  )
  values (
    v_customer_name, p_payment_method, v_items, v_total, auth.uid()
  )
  returning id into v_sale_id;

  return v_sale_id;
end;
$$;

revoke all on function public.complete_coffee_shop_sale(jsonb, text, text) from public, anon;
grant execute on function public.complete_coffee_shop_sale(jsonb, text, text) to authenticated;
