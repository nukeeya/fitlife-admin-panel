-- =============================================================================
-- 022: Door machine (ZKTeco SenseFace 3A) scans reach the database
-- =============================================================================
-- The machine pushes every scan to our receiver (supabase/functions/iclock).
--
--   * devices: machines we accept data from, matched by serial number.
--   * members.device_user_id: the user number on the machine ("pin") -> member.
--   * device_punches: every access record exactly as the machine sent it.
--     The machine resends after a failure, so duplicates are ignored.
--   * record_device_scans(): saves punches and creates attendance. A member gets
--     one attendance row per Dhaka day, however many times they scan.
--
-- Faces, fingerprints and photos are enrolled on the machine. It also sends
-- copies to the server; the receiver discards them, and no table here holds them.
--
-- Only the receiver can write scans (service role). Staff can read them; only a
-- Super Admin can add or change a machine.
--
-- Run after 021.

begin;

-- 1. Machines -------------------------------------------------------------------
create table if not exists public.devices (
  id             bigint generated by default as identity primary key,
  serial_number  text not null unique,
  name           text not null,
  location       text,
  model          text,
  firmware       text,
  ip_address     text,
  enabled        boolean not null default true,
  last_seen_at   timestamptz,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);

drop trigger if exists trg_devices_updated_at on public.devices;
create trigger trg_devices_updated_at
  before update on public.devices
  for each row execute function public.set_updated_at();

insert into public.devices (serial_number, name, location, model)
values ('VGU6262500121', 'Main Entrance', 'Main Entrance', 'SenseFace 3A')
on conflict (serial_number) do nothing;

-- 2. Machine user number on members ---------------------------------------------
alter table public.members add column if not exists device_user_id text;

alter table public.members drop constraint if exists members_device_user_id_check;
alter table public.members add constraint members_device_user_id_check
  check (device_user_id ~ '^[1-9][0-9]*$');

create unique index if not exists uq_members_device_user_id
  on public.members(device_user_id) where device_user_id is not null;

-- 3. Raw access records ---------------------------------------------------------
-- device_user_id is '0' for door events with no person (exit button, door alarm).
-- Deleting a device is deliberately not offered: disable it to keep its history.
create table if not exists public.device_punches (
  id             bigint generated by default as identity primary key,
  device_id      bigint not null references public.devices(id) on delete restrict,
  device_user_id text not null,
  member_id      bigint references public.members(id) on delete set null,
  punched_at     timestamptz not null,
  event_code     int not null,
  verify_type    int,
  in_out         int,
  card_no        text,
  log_index      bigint,
  attendance_id  bigint references public.attendance(id) on delete set null,
  received_at    timestamptz not null default now(),
  unique (device_id, punched_at, device_user_id, event_code)
);

create index if not exists idx_device_punches_time on public.device_punches(punched_at desc);
create index if not exists idx_device_punches_member on public.device_punches(member_id);

-- 4. Attendance dates in Dhaka time, not UTC ------------------------------------
alter table public.attendance
  alter column attendance_date set default ((now() at time zone 'Asia/Dhaka')::date),
  alter column check_in_time   set default ((now() at time zone 'Asia/Dhaka')::time);

-- 5. Which machine events mean the person was let in ----------------------------
-- 3 was confirmed on our SenseFace 3A: a face scan that opened the door.
-- 0 and 1 are ZKTeco's normal-entry codes. Change this list if the machine
-- reports another code for a successful fingerprint or card.
create or replace function public.device_event_grants_entry(p_event_code int)
returns boolean
language sql
immutable
as $$
  select p_event_code in (0, 1, 3);
$$;

-- 6. Receiver functions ---------------------------------------------------------
-- Called on each machine request. True when the serial is registered and enabled.
-- last_seen_at is only rewritten every 20 seconds to keep writes low.
create or replace function public.device_heartbeat(
  p_serial   text,
  p_ip       text default null,
  p_firmware text default null
)
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  update public.devices
     set last_seen_at = now(),
         ip_address   = coalesce(p_ip, ip_address),
         firmware     = coalesce(p_firmware, firmware)
   where serial_number = p_serial
     and enabled
     and (last_seen_at is null
          or last_seen_at < now() - interval '20 seconds'
          or p_ip is not null
          or p_firmware is not null);

  return exists (select 1 from public.devices where serial_number = p_serial and enabled);
end;
$$;

-- p_rows: [{ "local_time": "2026-11-08 17:25:06", "pin": "1", "event": 3,
--            "verify": 15, "in_out": 0, "card": null, "log_index": 5 }]
-- The machine's clock is Dhaka time. Returns how many new records were saved.
create or replace function public.record_device_scans(p_serial text, p_rows jsonb)
returns int
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_device_id     bigint;
  v_row           record;
  v_local         timestamp;
  v_date          date;
  v_member_id     bigint;
  v_punch_id      bigint;
  v_attendance_id bigint;
  v_saved         int := 0;
begin
  select id into v_device_id
    from public.devices
   where serial_number = p_serial and enabled;

  if v_device_id is null then
    raise exception 'Unknown or disabled device.' using errcode = '42501';
  end if;

  for v_row in
    select *
      from jsonb_to_recordset(p_rows) as x(
        local_time text, pin text, event int, verify int, in_out int, card text, log_index bigint
      )
  loop
    v_local := v_row.local_time::timestamp;
    v_date  := v_local::date;

    v_member_id := null;
    if v_row.pin <> '0' then
      select id into v_member_id from public.members where device_user_id = v_row.pin;
    end if;

    v_punch_id := null;
    insert into public.device_punches (
      device_id, device_user_id, member_id, punched_at,
      event_code, verify_type, in_out, card_no, log_index
    )
    values (
      v_device_id, v_row.pin, v_member_id, v_local at time zone 'Asia/Dhaka',
      v_row.event, v_row.verify, v_row.in_out, v_row.card, v_row.log_index
    )
    on conflict (device_id, punched_at, device_user_id, event_code) do nothing
    returning id into v_punch_id;

    continue when v_punch_id is null;  -- the machine resent this record
    v_saved := v_saved + 1;

    continue when v_member_id is null or not public.device_event_grants_entry(v_row.event);

    -- Two requests for the same member and day must not both insert.
    perform pg_advisory_xact_lock(hashtextextended(format('attendance:%s:%s', v_member_id, v_date), 0));

    v_attendance_id := null;
    select id into v_attendance_id
      from public.attendance
     where member_id = v_member_id and attendance_date = v_date
     order by id
     limit 1;

    if v_attendance_id is null then
      insert into public.attendance (member_id, attendance_date, check_in_time, status, method)
      values (
        v_member_id, v_date, v_local::time, 'In',
        case when v_row.verify = 4 then 'RFID Card' else 'Biometric' end
      )
      returning id into v_attendance_id;
    end if;

    update public.device_punches set attendance_id = v_attendance_id where id = v_punch_id;
  end loop;

  return v_saved;
end;
$$;

revoke all on function public.device_heartbeat(text, text, text) from public, anon, authenticated;
revoke all on function public.record_device_scans(text, jsonb) from public, anon, authenticated;
grant execute on function public.device_heartbeat(text, text, text) to service_role;
grant execute on function public.record_device_scans(text, jsonb) to service_role;

-- 7. Access ---------------------------------------------------------------------
alter table public.devices enable row level security;
alter table public.device_punches enable row level security;

grant select, insert, update on public.devices to authenticated;
grant select on public.device_punches to authenticated;

drop policy if exists "staff read devices" on public.devices;
create policy "staff read devices" on public.devices
  for select to authenticated using (public.is_staff());

drop policy if exists "super admin insert devices" on public.devices;
create policy "super admin insert devices" on public.devices
  for insert to authenticated with check (public.is_super_admin());

drop policy if exists "super admin update devices" on public.devices;
create policy "super admin update devices" on public.devices
  for update to authenticated using (public.is_super_admin()) with check (public.is_super_admin());

drop policy if exists "staff read device punches" on public.device_punches;
create policy "staff read device punches" on public.device_punches
  for select to authenticated using (public.is_staff());

commit;

