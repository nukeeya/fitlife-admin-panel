-- 027: Temporary notes while proving remote fingerprint enrollment
-- =============================================================================
-- Records the field names, numeric labels and length of a biometric upload.
-- Never the template itself. Supabase's function logs didn't show these lines,
-- so they are kept here to read from the SQL Editor.
--
-- Drop this table and function once fingerprints work.
--
-- Run after 026.

begin;

create table if not exists public.device_bio_upload_notes (
  id          bigint generated by default as identity primary key,
  note        text not null,
  received_at timestamptz not null default now()
);

-- No policies: only the SQL Editor and the receiver can reach it.
alter table public.device_bio_upload_notes enable row level security;

create or replace function public.note_bio_upload(p_note text)
returns void
language sql
security definer
set search_path = public, pg_temp
as $$
  insert into public.device_bio_upload_notes (note) values (left(p_note, 300));
$$;

revoke all on function public.note_bio_upload(text) from public, anon, authenticated;
grant execute on function public.note_bio_upload(text) to service_role;

commit;
