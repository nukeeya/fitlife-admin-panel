-- =============================================================================
-- 012 — PERSIST FINANCE MODULE STATE
-- =============================================================================
-- Run AFTER 011. Until now the Accounts / finance screens kept due-date
-- extensions, monthly closings, period adjustments and custom expense
-- categories in browser memory only (lost on refresh). This migration adds:
--
--   1. Expense columns the expense form already collects (vendor, approval).
--   2. One-time due-date extension columns on invoices + an RPC that enforces
--      the single-use rule on the server.
--   3. finance_month_closings, finance_period_adjustments, expense_categories.
--   4. A trigger that blocks expense writes dated inside a closed month.
--
-- Access follows 011: finance roles (staff_can('finances')) read and write;
-- only Super Admin can delete or re-open a closed month.
-- =============================================================================

begin;

-- -----------------------------------------------------------------------------
-- 1. EXPENSES — fields the expense form collects
-- -----------------------------------------------------------------------------
alter table public.expenses
  add column if not exists vendor text,
  add column if not exists approval_status text not null default 'Approved',
  add column if not exists approved_by_name text;

alter table public.expenses drop constraint if exists expenses_approval_status_check;
alter table public.expenses
  add constraint expenses_approval_status_check check (approval_status in ('Approved', 'Pending'));

-- -----------------------------------------------------------------------------
-- 2. ONE-TIME DUE-DATE EXTENSIONS
-- -----------------------------------------------------------------------------
alter table public.invoices
  add column if not exists original_due_date date,
  add column if not exists due_extended_at timestamptz,
  add column if not exists due_extension_reason text,
  add column if not exists due_extended_by bigint references public.users(id) on delete set null,
  add column if not exists due_extended_by_name text;

create or replace function public.extend_invoice_due_date(
  p_invoice_id   bigint,
  p_new_due_date date,
  p_reason       text,
  p_authorized_by text default null
)
returns public.invoices
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_invoice public.invoices%rowtype;
begin
  if not public.staff_can('finances') then
    raise exception 'Your account is not allowed to extend due dates.' using errcode = '42501';
  end if;
  if char_length(trim(coalesce(p_reason, ''))) = 0 then
    raise exception 'An extension reason is required.';
  end if;

  select * into v_invoice from public.invoices where id = p_invoice_id for update;
  if not found then
    raise exception 'Invoice not found.';
  end if;
  if v_invoice.due_extended_at is not null then
    raise exception 'Extension already used: only one due-date extension is allowed per invoice.';
  end if;
  if v_invoice.due_amount <= 0 then
    raise exception 'This invoice has no outstanding balance.';
  end if;
  if p_new_due_date is null or (v_invoice.due_date is not null and p_new_due_date <= v_invoice.due_date) then
    raise exception 'New due date must be after the current due date (%).', v_invoice.due_date;
  end if;

  update public.invoices
     set original_due_date    = v_invoice.due_date,
         due_date             = p_new_due_date,
         due_extended_at      = now(),
         due_extension_reason = trim(p_reason),
         due_extended_by      = public.current_staff_id(),
         due_extended_by_name = nullif(trim(coalesce(p_authorized_by, '')), '')
   where id = p_invoice_id
  returning * into v_invoice;

  return v_invoice;
end;
$$;

revoke all on function public.extend_invoice_due_date(bigint, date, text, text) from public, anon;
grant execute on function public.extend_invoice_due_date(bigint, date, text, text) to authenticated;

-- -----------------------------------------------------------------------------
-- 3. NEW FINANCE TABLES
-- -----------------------------------------------------------------------------
create table if not exists public.expense_categories (
  id         bigint generated by default as identity primary key,
  name       text not null check (char_length(trim(name)) between 1 and 80),
  created_by bigint references public.users(id) on delete set null,
  created_at timestamptz default now()
);
create unique index if not exists expense_categories_name_ci
  on public.expense_categories (lower(trim(name)));

create table if not exists public.finance_month_closings (
  month_key      text primary key check (month_key ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  closed_at      timestamptz not null default now(),
  closed_by      bigint references public.users(id) on delete set null,
  closed_by_name text,
  notes          text,
  summary        jsonb not null default '{}'::jsonb
);

create table if not exists public.finance_period_adjustments (
  id             bigint generated by default as identity primary key,
  month_key      text not null check (month_key ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  adjustment_type text not null check (adjustment_type in ('credit', 'debit', 'reclassification')),
  amount         numeric(12, 2) not null check (amount > 0),
  reason         text not null check (char_length(trim(reason)) > 0),
  authorized_by  text,
  created_by     bigint references public.users(id) on delete set null,
  created_at     timestamptz default now()
);
create index if not exists idx_finance_adjustments_month
  on public.finance_period_adjustments (month_key);

alter table public.expense_categories enable row level security;
alter table public.finance_month_closings enable row level security;
alter table public.finance_period_adjustments enable row level security;

-- expense_categories: finance roles read/add; Super Admin deletes.
drop policy if exists "staff read expense_categories" on public.expense_categories;
create policy "staff read expense_categories" on public.expense_categories
  for select to authenticated using (public.staff_can('finances'));
drop policy if exists "staff insert expense_categories" on public.expense_categories;
create policy "staff insert expense_categories" on public.expense_categories
  for insert to authenticated with check (public.staff_can('finances'));
drop policy if exists "staff delete expense_categories" on public.expense_categories;
create policy "staff delete expense_categories" on public.expense_categories
  for delete to authenticated using (public.is_super_admin());

-- finance_month_closings: finance roles read/close; only Super Admin re-opens.
-- No update policy: a closing record is immutable once written.
drop policy if exists "staff read finance_month_closings" on public.finance_month_closings;
create policy "staff read finance_month_closings" on public.finance_month_closings
  for select to authenticated using (public.staff_can('finances'));
drop policy if exists "staff insert finance_month_closings" on public.finance_month_closings;
create policy "staff insert finance_month_closings" on public.finance_month_closings
  for insert to authenticated with check (public.staff_can('finances'));
drop policy if exists "staff delete finance_month_closings" on public.finance_month_closings;
create policy "staff delete finance_month_closings" on public.finance_month_closings
  for delete to authenticated using (public.is_super_admin());

-- finance_period_adjustments: append-only audit log for finance roles.
drop policy if exists "staff read finance_period_adjustments" on public.finance_period_adjustments;
create policy "staff read finance_period_adjustments" on public.finance_period_adjustments
  for select to authenticated using (public.staff_can('finances'));
drop policy if exists "staff insert finance_period_adjustments" on public.finance_period_adjustments;
create policy "staff insert finance_period_adjustments" on public.finance_period_adjustments
  for insert to authenticated with check (public.staff_can('finances'));

grant select, insert, delete on public.expense_categories to authenticated;
grant select, insert, delete on public.finance_month_closings to authenticated;
grant select, insert on public.finance_period_adjustments to authenticated;
grant usage, select on sequence public.expense_categories_id_seq to authenticated;
grant usage, select on sequence public.finance_period_adjustments_id_seq to authenticated;

-- Fill closed_by from the session so the browser cannot claim to be someone else.
create or replace function public.set_finance_actor()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if tg_table_name = 'finance_month_closings' then
    new.closed_by := public.current_staff_id();
    new.closed_at := now();
  else
    new.created_by := public.current_staff_id();
    new.created_at := now();
  end if;
  return new;
end;
$$;

drop trigger if exists trg_month_closings_actor on public.finance_month_closings;
create trigger trg_month_closings_actor before insert on public.finance_month_closings
  for each row execute function public.set_finance_actor();
drop trigger if exists trg_period_adjustments_actor on public.finance_period_adjustments;
create trigger trg_period_adjustments_actor before insert on public.finance_period_adjustments
  for each row execute function public.set_finance_actor();
drop trigger if exists trg_expense_categories_actor on public.expense_categories;
create trigger trg_expense_categories_actor before insert on public.expense_categories
  for each row execute function public.set_finance_actor();

-- -----------------------------------------------------------------------------
-- 4. LOCK EXPENSES IN CLOSED MONTHS
-- -----------------------------------------------------------------------------
create or replace function public.block_closed_period_expense()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_months text[];
begin
  if tg_op in ('UPDATE', 'DELETE') then
    v_months := array[to_char(old.expense_date, 'YYYY-MM')];
  end if;
  if tg_op in ('INSERT', 'UPDATE') then
    v_months := coalesce(v_months, '{}') || to_char(new.expense_date, 'YYYY-MM');
  end if;

  if exists (select 1 from public.finance_month_closings where month_key = any(v_months)) then
    raise exception 'This expense falls in a closed accounting month. Record a period adjustment instead.';
  end if;

  return coalesce(new, old);
end;
$$;

drop trigger if exists trg_expenses_closed_period on public.expenses;
create trigger trg_expenses_closed_period
  before insert or update or delete on public.expenses
  for each row execute function public.block_closed_period_expense();

commit;
