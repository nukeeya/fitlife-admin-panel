-- =============================================================================
-- 017: Visitors (walk-in visitor log for the Visitor Entry page)
-- =============================================================================
-- One row per visit: prospective members touring the gym, one-day trial
-- guests and general visitors. Money is not recorded here: day passes and
-- trials will be charged through invoices/payments so Finance sees them.
--
-- - visit_date / visit_time default to now in Dhaka time; staff can change them.
-- - handled_by is always the signed-in staff member (set by a trigger, so it
--   cannot be typed in or faked from the browser).
-- - member_id links the visitor to the member they became, if any.
-- - Any staff member can view, add and edit visitors; only Super Admin deletes.
--
-- Run after 016.

create table if not exists public.visitors (
  id            bigint generated by default as identity primary key,
  name          text not null check (char_length(trim(name)) between 2 and 120),
  phone         text not null check (char_length(trim(phone)) between 6 and 30),
  visit_date    date not null default ((now() at time zone 'Asia/Dhaka')::date),
  visit_time    time not null default ((now() at time zone 'Asia/Dhaka')::time),
  visitor_type  text not null default 'Prospective Member'
                check (visitor_type in ('Prospective Member', 'One-Day Trial', 'General Visit')),
  status        text not null default 'Inquiry'
                check (status in ('Inquiry', 'Checked In', 'Completed', 'Converted to Member')),
  notes         text,
  handled_by    bigint references public.users(id) on delete set null,
  member_id     bigint references public.members(id) on delete set null,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

create index if not exists visitors_visit_date_idx on public.visitors (visit_date desc);

-- handled_by: the staff member who logged the visit, set on insert only.
create or replace function public.set_visitor_handled_by()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  new.handled_by := public.current_staff_id();
  return new;
end;
$$;

drop trigger if exists trg_visitors_handled_by on public.visitors;
create trigger trg_visitors_handled_by
  before insert on public.visitors
  for each row execute function public.set_visitor_handled_by();

drop trigger if exists trg_visitors_updated_at on public.visitors;
create trigger trg_visitors_updated_at
  before update on public.visitors
  for each row execute function public.set_updated_at();

-- Access: same pattern as the other staff tables (migration 011).
alter table public.visitors enable row level security;

drop policy if exists "staff read visitors" on public.visitors;
create policy "staff read visitors" on public.visitors
  for select to authenticated using (public.is_staff());

drop policy if exists "staff insert visitors" on public.visitors;
create policy "staff insert visitors" on public.visitors
  for insert to authenticated with check (public.is_staff());

drop policy if exists "staff update visitors" on public.visitors;
create policy "staff update visitors" on public.visitors
  for update to authenticated using (public.is_staff()) with check (public.is_staff());

drop policy if exists "staff delete visitors" on public.visitors;
create policy "staff delete visitors" on public.visitors
  for delete to authenticated using (public.is_super_admin());
